def _region_of(text):
    first = (text or "").strip().split(" ")[0]
    return _ALIASES.get(first)


def classify_region(rdnmadr, lnmadr, instt_nm):
    """도로명주소 → 지번주소 → 등록기관명 순서로 시도명을 찾는다."""
    for text in (rdnmadr, lnmadr, instt_nm):
        region = _region_of(text)
        if region:
            return region
    return REGION_OTHER
